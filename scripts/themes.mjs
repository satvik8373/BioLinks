import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs'
import { resolve, join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv from 'ajv'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schema = JSON.parse(readFileSync(join(projectRoot, 'lib/theme-engine/schemas/theme.schema.json'), 'utf8'))
const ajv = new Ajv({ allErrors: true, strict: false })
const validate = ajv.compile(schema)
const safeId = /^[a-z0-9]+(?:-[a-z0-9]+)*$/

export function readThemes(root = projectRoot) {
  const themesDir = join(root, 'themes')
  const themes = readdirSync(themesDir, { withFileTypes: true })
    .filter(entry => entry.isDirectory() && !entry.name.startsWith('_'))
    .map(entry => {
      const file = join(themesDir, entry.name, 'config.json')
      if (!existsSync(file)) throw new Error(`${entry.name}: missing config.json`)
      const config = JSON.parse(readFileSync(file, 'utf8'))
      if (!validate(config)) throw new Error(`${entry.name}: ${ajv.errorsText(validate.errors)}`)
      if (config.id !== entry.name) throw new Error(`${entry.name}: config.id must match its folder`)
      if (config.id === 'custom') throw new Error('custom is reserved for user customization')
      return config
    })
  if (!themes.length || !themes.some(theme => theme.id === 'pop-brutalist')) throw new Error('Missing default theme pop-brutalist')
  return themes.sort((a, b) => {
    if (a.id === 'pop-brutalist') return -1
    if (b.id === 'pop-brutalist') return 1
    return (a.order ?? 100) - (b.order ?? 100) || a.id.localeCompare(b.id)
  })
}

export function generateThemes(root = projectRoot, check = false) {
  const themes = readThemes(root)
  const imports = themes.map((theme, i) => `import theme${i} from './${theme.id}/config.json'`).join('\n')
  const module = `// Generated by npm run themes:sync. Do not edit.\nimport type { ThemeConfig } from '@/lib/theme-engine/types'\n${imports}\n\n// The CLI validates every config against the shared schema before generation.\nexport const ALL_JSON_CONFIGS = [${themes.map((_, i) => `theme${i}`).join(', ')}] as ThemeConfig[]\n`
  const styles = '/* Generated by npm run themes:sync. Do not edit. */\n' + themes
    .filter(theme => existsSync(join(root, 'themes', theme.id, 'styles.css')))
    .map(theme => `@import './${theme.id}/styles.css';\n`).join('')
  const manifest = JSON.stringify({ version: '2.1.0', themes: themes.map(theme => ({
    id: theme.id, name: theme.name, category: theme.category,
    license: theme.isPro ? 'pro' : (typeof theme.license === 'string' ? theme.license : theme.license?.type || 'free'),
    isCurated: Boolean(theme.isCurated ?? theme.meta?.isCurated),
    ...(theme.preview?.thumbnail && { preview: theme.preview.thumbnail }),
  })) }, null, 2) + '\n'
  for (const [file, content] of [['generated.ts', module], ['generated.css', styles], ['manifest.json', manifest]]) {
    const path = join(root, 'themes', file)
    if (check) {
      if (!existsSync(path) || readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== content) {
        throw new Error(`${file} is stale. Run npm run themes:sync.`)
      }
    } else if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      writeFileSync(path, content)
    }
  }
  return themes
}

export function createTheme(id, { from = 'pop-brutalist', name } = {}, root = projectRoot) {
  if (!safeId.test(id || '') || id.length > 80 || id === 'custom') throw new Error('Use a unique kebab-case ID (custom is reserved).')
  if (!safeId.test(from)) throw new Error('Invalid source theme ID.')
  const themes = readThemes(root)
  const source = themes.find(theme => theme.id === from)
  if (!source) throw new Error(`Unknown source theme: ${from}`)
  const target = join(root, 'themes', id)
  if (existsSync(target)) throw new Error(`Theme ${id} already exists; nothing was overwritten.`)
  const config = {
    ...structuredClone(source), id, name: name || id.split('-').map(word => word[0].toUpperCase() + word.slice(1)).join(' '),
    namespace: `theme-${id}`, order: Math.max(...themes.map(theme => theme.order || 0)) + 1,
    isCurated: false,
    meta: { author: 'BioLinks', description: `Custom theme based on ${source.name}.`, tags: [id] },
  }
  delete config.preview
  if (!validate(config)) throw new Error(ajv.errorsText(validate.errors))
  mkdirSync(target)
  writeFileSync(join(target, 'config.json'), JSON.stringify(config, null, 2) + '\n')
  generateThemes(root)
  return config
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const [command = 'sync', ...args] = process.argv.slice(2)
    if (command === 'create') {
      const [id, ...flags] = args
      const options = {}
      for (let i = 0; i < flags.length; i += 2) {
        if (!['--from', '--name'].includes(flags[i]) || !flags[i + 1]) throw new Error('Usage: npm run theme:create -- <id> [--from <id>] [--name "Theme Name"]')
        options[flags[i].slice(2)] = flags[i + 1]
      }
      const theme = createTheme(id, options)
      console.log(`Created themes/${theme.id}/config.json and registered it. Edit this file to customize the theme.`)
    } else if (['sync', 'check'].includes(command)) {
      console.log(`${generateThemes(projectRoot, command === 'check').length} themes validated${command === 'check' ? '; registry is current' : ' and registered'}.`)
    } else throw new Error(`Unknown command: ${command}`)
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
